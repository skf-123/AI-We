/**
 * 提示词 —— 本项目的核心资产。
 *
 * 产品定位是「零提示词」：用户只粘贴代码，什么都不用问。
 * 所以全部的引导责任都落在这份系统提示词上：它把"用户不知道该怎么问"
 * 这件事，翻译成"必须自动输出的四个部分"。
 *
 * 四个部分对应需求文档里的主流程：
 *   一、逐词逐句  → 每一行在干什么
 *   二、局部关系  → 小段之间怎么衔接、数据怎么流动
 *   三、整段作用  → 整体解决什么问题、什么场景用
 *   四、技术溯源  → 用了什么技术、为什么被发明、怎么演化（防 AI 编造）
 */

